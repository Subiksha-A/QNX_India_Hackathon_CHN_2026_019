/* ========================================================================== */
/* NXP command helper                                                         */
/* ========================================================================== */

static void send_start_stop(
    uint8_t node_id,
    uint8_t command)
{
    gateway_frame_t frame;

    memset(&frame,
           0,
           sizeof(frame));

    frame.can_id =
        (node_id == NODE1_ID) ?
            NODE1_CMD_ID :
            NODE2_CMD_ID;

    frame.dlc =
        8U;

    frame.data[0] =
        command;

    frame.source_bus =
        255U;

    frame.target_bus =
        (node_id == NODE1_ID) ?
            0U :
            1U;

    frame.node_id =
        node_id;

    frame.rx_timestamp_ns =
        monotonic_ns();

    if (safety_push(
            &frame)) {

        printf(
            "[MASTER] Node %u command 0x%02X queued on CAN%u\n",
            node_id,
            command,
            frame.target_bus);
    }
}

