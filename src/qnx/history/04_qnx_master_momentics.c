static const char *sensor_name(
    sensor_type_t sensor)
{
    switch (sensor) {

        case SENSOR_TEMPERATURE:
            return "Temperature";

        case SENSOR_HUMIDITY:
            return "Humidity";

        case SENSOR_SPEED:
            return "Speed";

        case SENSOR_BATTERY_VOLTAGE:
            return "BatteryVoltage";

        case SENSOR_BATTERY_CURRENT:
            return "BatteryCurrent";

        case SENSOR_ULTRASONIC:
            return "Ultrasonic";

        case SENSOR_IR:
            return "IR";

        default:
            return "Unknown";
    }
}

static uint32_t sensor_address(
    uint8_t node_id,
    sensor_type_t sensor)
{
    uint32_t base =
        (node_id == NODE1_ID) ?
            0x1000U :
            0x2000U;

    return base +
           ((uint32_t)sensor * 0x10U);
}

static bool decode_sensor(
    const gateway_frame_t *frame,
    sensor_type_t *sensor,
    float *value,
    uint8_t *node_id)
{
    uint16_t raw;

    if (frame == NULL ||
        sensor == NULL ||
        value == NULL ||
        node_id == NULL ||
        frame->dlc < 4U) {

        return false;
    }

    *node_id =
        frame->data[3];

    switch (frame->can_id) {

        case 0x111U:
        case 0x121U:
            *sensor =
                SENSOR_TEMPERATURE;
            break;

        case 0x112U:
        case 0x122U:
            *sensor =
                SENSOR_HUMIDITY;
            break;

        case 0x113U:
        case 0x123U:
            *sensor =
                SENSOR_SPEED;
            break;

        case 0x114U:
        case 0x124U:
            *sensor =
                SENSOR_BATTERY_VOLTAGE;
            break;

        case 0x115U:
        case 0x125U:
            *sensor =
                SENSOR_BATTERY_CURRENT;
            break;

        case 0x116U:
            *sensor =
                SENSOR_ULTRASONIC;
            break;

        case 0x117U:
            *sensor =
                SENSOR_IR;

            *value =
                frame->data[0] ?
                    1.0f :
                    0.0f;

            return true;

        case 0x126U:
            /*
             * Optional Node-2 ultrasonic extension if the MCXA236
             * firmware is extended using the Node-1 convention.
             */
            *sensor =
                SENSOR_ULTRASONIC;
            break;

        case 0x127U:
            /*
             * Optional Node-2 IR extension.
             */
            *sensor =
                SENSOR_IR;

            *value =
                frame->data[0] ?
                    1.0f :
                    0.0f;

            return true;

        default:
            return false;
    }

    raw =
        ((uint16_t)frame->data[0] << 8) |
        ((uint16_t)frame->data[1]);

    *value =
        (float)raw / 100.0f;

    return true;
}

static float prediction_tolerance(
    sensor_type_t sensor)
{
    switch (sensor) {

        case SENSOR_TEMPERATURE:
            return 0.50f;

        case SENSOR_HUMIDITY:
            return 2.0f;

        case SENSOR_SPEED:
            return 5.0f;

        case SENSOR_BATTERY_VOLTAGE:
            return 0.20f;

        case SENSOR_BATTERY_CURRENT:
            return 0.50f;

        case SENSOR_ULTRASONIC:
            return 15.0f;

        case SENSOR_IR:
            return 0.0f;

        default:
            return 0.0f;
    }
}

static void update_sensor_state(
    uint8_t node_id,
    sensor_type_t sensor,
    float value,
    uint32_t can_id,
    uint64_t timestamp_ns)
{
    latest_sensor_state_t *state;

    (void)node_id;

    state =
        &g_latest_state[sensor];

    state->valid =
        true;

    state->node_id =
        node_id;

    state->sensor =
        sensor;

    state->value =
        value;

    state->can_id =
        can_id;

    state->logical_addr =
        sensor_address(node_id,
                       sensor);

    state->timestamp_ns =
        timestamp_ns;
}

/* ========================================================================== */
/* Prediction engine                                                          */
/* ========================================================================== */

/*
 * Prediction:
 *
 *   predicted[n] =
 *       x[n-1] + (x[n-1] - x[n-2])
 *
 * Actual NXP reading:
 *   reference / correction
 *
 * This is deliberately a lightweight deterministic predictor.
 * The supplied NXP firmware is a sensor publisher, not an AI model.
 */
static void analyze_prediction(
    uint8_t node_id,
    sensor_type_t sensor,
    float actual,
    uint32_t can_id,
    uint64_t timestamp_ns)
{
    float predicted;
    float error_value;
    float tolerance;

    prediction_record_t record;

    if (!g_history_valid[sensor]) {

        g_prev_value[sensor] =
            actual;

        g_last_value[sensor] =
            actual;

        g_history_valid[sensor] =
            true;

        return;
    }

    predicted =
        g_last_value[sensor] +
        (g_last_value[sensor] -
         g_prev_value[sensor]);

    error_value =
        fabsf(actual -
              predicted);

    tolerance =
        prediction_tolerance(sensor);

    record.valid =
        true;

    record.node_id =
        node_id;

    record.sensor =
        sensor;

    record.can_id =
        can_id;

    record.logical_addr =
        sensor_address(node_id,
                       sensor);

    record.predicted =
        predicted;

    record.actual =
        actual;

    record.error =
        error_value;

    record.tolerance =
        tolerance;

    record.timestamp_ns =
        timestamp_ns;

    record.sequence =
        g_prediction_sequence++;

    g_prev_value[sensor] =
        g_last_value[sensor];

    g_last_value[sensor] =
        actual;

    pthread_mutex_lock(
        &g_stats.lock);

    ++g_stats.prediction_total;

    pthread_mutex_unlock(
        &g_stats.lock);

    if (error_value >
        tolerance) {

        /*
         * WRONG:
         * retain the event historically.
         */
        if (error_push(
                &record)) {

            pthread_mutex_lock(
                &g_memory_bus_lock);

            pthread_mutex_lock(
                &g_stats.lock);

            ++g_stats.memory_bus_writes;
            ++g_stats.prediction_wrong;

            pthread_mutex_unlock(
                &g_stats.lock);

            pthread_mutex_unlock(
                &g_memory_bus_lock);
        }

    } else {

        /*
         * CORRECT:
         * overwrite the previous correct state.
         */
        latest_corrected_publish(
            &record);

        pthread_mutex_lock(
            &g_memory_bus_lock);

        pthread_mutex_lock(
            &g_stats.lock);

        ++g_stats.memory_bus_writes;
        ++g_stats.prediction_correct;

        pthread_mutex_unlock(
            &g_stats.lock);

        pthread_mutex_unlock(
            &g_memory_bus_lock);
    }
}

/* ========================================================================== */
/* Safety command generation                                                  */
/* ========================================================================== */

static void request_stop(
    uint8_t node_id,
    uint8_t bus,
    const char *reason,
    uint64_t source_timestamp_ns)
{
    gateway_frame_t command;

    bool *latched =
        (node_id == NODE1_ID) ?
            &g_safety_latched_node1 :
            &g_safety_latched_node2;

    if (*latched) {
        return;
    }

    memset(&command,
           0,
           sizeof(command));

    command.can_id =
        (node_id == NODE1_ID) ?
            NODE1_CMD_ID :
            NODE2_CMD_ID;

    command.dlc =
        8U;

    command.data[0] =
        CMD_STOP;

    command.source_bus =
        bus;

    command.target_bus =
        bus;

    command.node_id =
        node_id;

    command.rx_timestamp_ns =
        source_timestamp_ns;

    command.logical_addr =
        0x0800U;

    if (safety_push(
            &command)) {

        *latched =
            true;

        pthread_mutex_lock(
            &g_stats.lock);

        ++g_stats.safety_events;

        pthread_mutex_unlock(
            &g_stats.lock);

        printf(
            "\n[SAFETY] Node %u STOP: %s\n",
            node_id,
            reason);
    }
}

static void clear_safety_latches(void)
{
    g_safety_latched_node1 =
        false;

    g_safety_latched_node2 =
        false;

    printf(
        "[SAFETY] latches cleared\n");
}

/* ========================================================================== */
/* CAN0 / CAN1 routing                                                        */
/* ========================================================================== */

static void route_sensor_frame(
    gateway_frame_t *frame)
{
    /*
     * A valid sensor frame received from CAN0 is forwarded to CAN1.
     * A valid sensor frame received from CAN1 is forwarded to CAN0.
     *
     * This creates the actual gateway behavior between two NXP CAN domains.
     */
    frame->target_bus =
        (frame->source_bus == 0U) ?
            1U :
            0U;

    if (!normal_push(frame)) {

        pthread_mutex_lock(
            &g_stats.lock);

        ++g_stats.tx_failures;

        pthread_mutex_unlock(
            &g_stats.lock);
    }
}

/* ========================================================================== */
/* MCP2515 SPI                                                                 */
/* ========================================================================== */

typedef union {
    uint64_t alignment;
    uint8_t raw[
        sizeof(spi_xchng_t) +
        MAX_SPI_BYTES];
} spi_buffer_t;

static int spi_xfer(
    int fd,
    const void *tx,
    void *rx,
    size_t length)
{
    spi_buffer_t storage;
    spi_xchng_t *exchange;

    uint32_t total;
    int rc;

    if (length >
        MAX_SPI_BYTES) {

        return EINVAL;
    }

    memset(&storage,
           0,
           sizeof(storage));

    exchange =
        (spi_xchng_t *)storage.raw;

    total =
        (uint32_t)(
            sizeof(spi_xchng_t) +
            length);

    exchange->nbytes =
        (uint32_t)length;

    if (tx != NULL) {

        memcpy(exchange->data,
               tx,
               length);
    }

    rc =
        devctl(fd,
               DCMD_SPI_DATA_XCHNG,
               exchange,
               total,
               NULL);

    if (rc == 0 &&
        rx != NULL) {

        memcpy(rx,
               exchange->data,
               length);
    }

    return rc;
}

static int mcp_write(
    int fd,
    uint8_t reg,
    uint8_t value)
{
    struct __attribute__((packed)) {
        uint8_t cmd;
        uint8_t reg;
        uint8_t value;
    } packet;

    packet.cmd =
        MCP_WRITE;

    packet.reg =
        reg;

    packet.value =
        value;

    return spi_xfer(
        fd,
        &packet,
        NULL,
        sizeof(packet));
}

static int mcp_read(
    int fd,
    uint8_t reg,
    uint8_t *value)
{
    struct __attribute__((packed)) {
        uint8_t cmd;
        uint8_t reg;
        uint8_t dummy;
    } tx;

    struct __attribute__((packed)) {
        uint8_t cmd;
        uint8_t reg;
        uint8_t dummy;
    } rx;

    memset(&tx,
           0,
           sizeof(tx));

    memset(&rx,
           0,
           sizeof(rx));

    tx.cmd =
        MCP_READ;

    tx.reg =
        reg;

    if (spi_xfer(
            fd,
            &tx,
            &rx,
            sizeof(tx)) != 0) {

        return EIO;
    }

    *value =
        rx.dummy;

    return 0;
}

static int mcp_bit_modify(
    int fd,
    uint8_t reg,
    uint8_t mask,
    uint8_t value)
{
    struct __attribute__((packed)) {
        uint8_t cmd;
        uint8_t reg;
        uint8_t mask;
        uint8_t value;
    } packet;

    packet.cmd =
        MCP_BITMOD;

    packet.reg =
        reg;

    packet.mask =
        mask;

    packet.value =
        value;

    return spi_xfer(
        fd,
        &packet,
        NULL,
        sizeof(packet));
}

/* ========================================================================== */
/* CAN initialization                                                        */
/* ========================================================================== */

static int init_can(
    const char *device,
    const char *name)
{
    int fd;
    spi_cfg_t cfg;
    uint8_t status;

    fd =
        open(device,
             O_RDWR);

    if (fd < 0) {

        fprintf(stderr,
                "[-] %s: open failed: %s\n",
                name,
                strerror(errno));

        return -1;
    }

    memset(&cfg,
           0,
           sizeof(cfg));

    cfg.mode =
        8U | (1U << 10);

    cfg.clock_rate =
        5000000U;

    if (devctl(
            fd,
            DCMD_SPI_SET_CONFIG,
            &cfg,
            sizeof(cfg),
            NULL) != 0) {

        fprintf(stderr,
                "[-] %s: SPI config failed\n",
                name);

        close(fd);

        return -1;
    }

    {
        uint8_t reset =
            MCP_RESET;

        if (spi_xfer(
                fd,
                &reset,
                NULL,
                1U) != 0) {

            fprintf(stderr,
                    "[-] %s: MCP reset failed\n",
                    name);

            close(fd);

            return -1;
        }
    }

    usleep(10000);

    /*
     * Existing project assumption:
     * MCP2515 = 16-MHz oscillator.
     * CNF values correspond to the existing 500-kbps project setup.
     */
    (void)mcp_write(
        fd,
        REG_CNF1,
        0x01U);

    (void)mcp_write(
        fd,
        REG_CNF2,
        0x90U);

    (void)mcp_write(
        fd,
        REG_CNF3,
        0x02U);

    /* Accept all standard IDs. */
    (void)mcp_write(
        fd,
        REG_RXM0SIDH,
        0x00U);

    (void)mcp_write(
        fd,
        REG_RXM0SIDL,
        0x00U);

    (void)mcp_write(
        fd,
        REG_RXM1SIDH,
        0x00U);

    (void)mcp_write(
        fd,
        REG_RXM1SIDL,
        0x00U);

    (void)mcp_write(
        fd,
        REG_RXB0CTRL,
        0x64U);

    (void)mcp_write(
        fd,
        REG_RXB1CTRL,
        0x60U);

    (void)mcp_write(
        fd,
        REG_CANINTE,
        0x03U);

    (void)mcp_bit_modify(
        fd,
        REG_CANCTRL,
        0xE0U,
        0x00U);

    status = 0U;

    (void)mcp_read(
        fd,
        REG_CANSTAT,
        &status);

    printf(
        "[+] %s initialized, CANSTAT=0x%02X\n",
        name,
        status);

    return fd;
}

/* ========================================================================== */
/* CAN receive                                                                */
/* ========================================================================== */

static int receive_can(
    int fd,
    uint8_t source_bus,
    gateway_frame_t *frame)
{
    uint8_t intf;
    uint8_t base_reg;

    struct __attribute__((packed)) {
        uint8_t cmd;
        uint8_t reg;
        uint8_t sidh;
        uint8_t sidl;
        uint8_t eid8;
        uint8_t eid0;
        uint8_t dlc;
        uint8_t data[8];
    } tx;

    struct __attribute__((packed)) {
        uint8_t cmd;
        uint8_t reg;
        uint8_t sidh;
        uint8_t sidl;
        uint8_t eid8;
        uint8_t eid0;
        uint8_t dlc;
        uint8_t data[8];
    } rx;

    if (mcp_read(
            fd,
            REG_CANINTF,
            &intf) != 0) {

        return -1;
    }

    if (intf & 0x01U) {

        base_reg =
            REG_RXB0SIDH;

    } else if (intf & 0x02U) {

        base_reg =
            REG_RXB1SIDH;

    } else {

        return 0;
    }

    memset(&tx,
           0,
           sizeof(tx));

    memset(&rx,
           0,
           sizeof(rx));

    tx.cmd =
        MCP_READ;

    tx.reg =
        base_reg;

    if (spi_xfer(
            fd,
            &tx,
            &rx,
            sizeof(tx)) != 0) {

        return -1;
    }

    memset(frame,
           0,
           sizeof(*frame));

    frame->can_id =
        ((uint32_t)rx.sidh << 3) |
        ((uint32_t)rx.sidl >> 5);

    frame->dlc =
        (uint8_t)(
            rx.dlc & 0x0FU);

    if (frame->dlc > 8U) {
        frame->dlc = 8U;
    }

    memcpy(frame->data,
           rx.data,
           frame->dlc);

    frame->rx_timestamp_ns =
        monotonic_ns();

    frame->source_bus =
        source_bus;

    frame->target_bus =
        (source_bus == 0U) ?
            1U :
            0U;

    if (base_reg ==
        REG_RXB0SIDH) {

        (void)mcp_bit_modify(
            fd,
            REG_CANINTF,
            0x01U,
            0x00U);

    } else {

        (void)mcp_bit_modify(
            fd,
            REG_CANINTF,
            0x02U,
            0x00U);
    }

    return 1;
}

/* ========================================================================== */
/* CAN transmit                                                               */
/* ========================================================================== */

static int tx_buffer(
    int fd,
    unsigned buffer,
    const gateway_frame_t *frame)
{
    uint8_t ctrl_reg;
    uint8_t data_reg;
    uint8_t tx_value;
    uint8_t ctrl;

    struct __attribute__((packed)) {
        uint8_t cmd;
        uint8_t reg;
        uint8_t sidh;
        uint8_t sidl;
        uint8_t eid8;
        uint8_t eid0;
        uint8_t dlc;
        uint8_t data[8];
    } packet;

    if (frame == NULL ||
        frame->dlc > 8U ||
        buffer > 2U) {

        return EINVAL;
    }

    if (buffer == 0U) {

        ctrl_reg =
            REG_TXB0CTRL;

        data_reg =
            REG_TXB0SIDH;

        tx_value =
            0x0BU;

    } else if (buffer == 1U) {

        ctrl_reg =
            REG_TXB1CTRL;

        data_reg =
            REG_TXB1SIDH;

        tx_value =
            0x0AU;

    } else {

        ctrl_reg =
            REG_TXB2CTRL;

        data_reg =
            REG_TXB2SIDH;

        tx_value =
            0x08U;
    }

    if (mcp_read(
            fd,
            ctrl_reg,
            &ctrl) != 0) {

        return EIO;
    }

    if (ctrl & 0x08U) {
        return EBUSY;
    }

    memset(&packet,
           0,
           sizeof(packet));

    packet.cmd =
        MCP_WRITE;

    packet.reg =
        data_reg;

    packet.sidh =
        (uint8_t)(
            frame->can_id >> 3);

    packet.sidl =
        (uint8_t)(
            frame->can_id << 5);

    packet.dlc =
        frame->dlc;

    memcpy(packet.data,
           frame->data,
           frame->dlc);

    if (spi_xfer(
            fd,
            &packet,
            NULL,
            7U + frame->dlc) != 0) {

        return EIO;
    }

    return mcp_write(
        fd,
        ctrl_reg,
        tx_value);
}

/* ========================================================================== */
/* THREAD: CAN0 RX                                                            */
/* ========================================================================== */

static void *can0_rx_thread(void *arg)
{
    (void)arg;

    pin_current_thread(1U);

    while (g_running) {

        gateway_frame_t frame;

        int rc =
            receive_can(
                g_can0,
                0U,
                &frame);

        if (rc <= 0) {

            usleep(RX_POLL_US);

            continue;
        }

        pthread_mutex_lock(
            &g_stats.lock);

        ++g_stats.rx_can0;

        pthread_mutex_unlock(
            &g_stats.lock);

        {
            sensor_type_t sensor;
            float value;
            uint8_t node_id;

            if (!decode_sensor(
                    &frame,
                    &sensor,
                    &value,
                    &node_id)) {

                /*
                 * Non-sensor CAN0 frames are still forwarded as
                 * low/normal traffic.
                 */
                frame.node_id = NODE1_ID;

                if (frame.can_id ==
                    NODE1_CMD_ID ||
                    frame.can_id ==
                    BROADCAST_CMD_ID) {

                    continue;
                }

                if (!normal_push(
                        &frame)) {

                    pthread_mutex_lock(
                        &g_stats.lock);

                    ++g_stats.tx_failures;

                    pthread_mutex_unlock(
                        &g_stats.lock);
                }

                continue;
            }

            frame.node_id =
                node_id;

            frame.sensor =
                sensor;

            frame.logical_addr =
                sensor_address(
                    node_id,
                    sensor);

            update_sensor_state(
                node_id,
                sensor,
                value,
                frame.can_id,
                frame.rx_timestamp_ns);

            analyze_prediction(
                node_id,
                sensor,
                value,
                frame.can_id,
                frame.rx_timestamp_ns);

            /*
             * Real safety sensors from Node 1.
             */
            if (sensor ==
                SENSOR_ULTRASONIC) {

                if (value > 0.0f &&
                    value <=
                    ULTRASONIC_STOP_CM) {

                    request_stop(
                        node_id,
                        0U,
                        "Node 1 ultrasonic distance <= safety threshold",
                        frame.rx_timestamp_ns);
                }

            } else if (sensor ==
                       SENSOR_IR) {

                if (value > 0.5f) {

                    request_stop(
                        node_id,
                        0U,
                        "Node 1 IR obstacle",
                        frame.rx_timestamp_ns);
                }
            }

            route_sensor_frame(
                &frame);
        }
    }

    return NULL;
}

/* ========================================================================== */
/* THREAD: CAN1 RX                                                            */
/* ========================================================================== */

static void *can1_rx_thread(void *arg)
{
    (void)arg;

    pin_current_thread(2U);

    while (g_running) {

        gateway_frame_t frame;

        int rc =
            receive_can(
                g_can1,
                1U,
                &frame);

        if (rc <= 0) {

            usleep(RX_POLL_US);

            continue;
        }

        pthread_mutex_lock(
            &g_stats.lock);

        ++g_stats.rx_can1;

        pthread_mutex_unlock(
            &g_stats.lock);

        {
            sensor_type_t sensor;
            float value;
            uint8_t node_id;

            if (!decode_sensor(
                    &frame,
                    &sensor,
                    &value,
                    &node_id)) {

                if (!normal_push(
                        &frame)) {

                    pthread_mutex_lock(
                        &g_stats.lock);

                    ++g_stats.tx_failures;

                    pthread_mutex_unlock(
                        &g_stats.lock);
                }

                continue;
            }

            frame.node_id =
                node_id;

            frame.sensor =
                sensor;

            frame.logical_addr =
                sensor_address(
                    node_id,
                    sensor);

            update_sensor_state(
                node_id,
                sensor,
                value,
                frame.can_id,
                frame.rx_timestamp_ns);

            analyze_prediction(
                node_id,
                sensor,
                value,
                frame.can_id,
                frame.rx_timestamp_ns);

            /*
             * These rules are available for optional Node-2 ultrasonic/IR
             * extensions. The supplied MCXA156 file establishes 0x116/0x117
             * on Node 1; the 0x126/0x127 cases above are gateway extensions
             * and must match your actual MCXA236 code before use.
             */
            if (sensor ==
                SENSOR_ULTRASONIC &&
                value > 0.0f &&
                value <=
                ULTRASONIC_STOP_CM) {

                request_stop(
                    node_id,
                    1U,
                    "Node 2 ultrasonic distance <= safety threshold",
                    frame.rx_timestamp_ns);

            } else if (
                sensor ==
                SENSOR_IR &&
                value > 0.5f) {

                request_stop(
                    node_id,
                    1U,
                    "Node 2 IR obstacle",
                    frame.rx_timestamp_ns);
            }

            route_sensor_frame(
                &frame);
        }
    }

    return NULL;
}

/* ========================================================================== */
/* THREAD: Safety task P60                                                    */
/* ========================================================================== */

static void *safety_thread(void *arg)
{
    (void)arg;

    pin_current_thread(0U);

    /*
     * Highest-priority safety monitor. It checks the already-decoded
     * Node-1 safety sensors. The CAN RX path also performs the immediate
     * check, while this task provides an independent safety-monitoring layer.
     *
     * No file I/O, gzip, dynamic allocation, or dashboard work occurs here.
     */
    while (g_running) {

        if (g_latest_state[SENSOR_ULTRASONIC].valid &&
            g_latest_state[SENSOR_ULTRASONIC].node_id == NODE1_ID &&
            g_latest_state[SENSOR_ULTRASONIC].value > 0.0f &&
            g_latest_state[SENSOR_ULTRASONIC].value <= ULTRASONIC_STOP_CM) {

            request_stop(
                NODE1_ID,
                0U,
                "P60 monitor: ultrasonic threshold",
                g_latest_state[SENSOR_ULTRASONIC].timestamp_ns);
        }

        if (g_latest_state[SENSOR_IR].valid &&
            g_latest_state[SENSOR_IR].node_id == NODE1_ID &&
            g_latest_state[SENSOR_IR].value > 0.5f) {

            request_stop(
                NODE1_ID,
                0U,
                "P60 monitor: IR obstacle",
                g_latest_state[SENSOR_IR].timestamp_ns);
        }

        /* Periodic 1-ms safety monitor; it must sleep to avoid starving P55. */
        usleep(1000U);
    }

    return NULL;
}

/* ========================================================================== */
/* THREAD: CAN0 TX scheduler P55                                              */
/* ========================================================================== */

static void *can0_tx_thread(void *arg)
{
    (void)arg;

    pin_current_thread(0U);

    while (g_running) {

        gateway_frame_t frame;

        /*
         * SAFETY FIRST on CAN0.
         */
        if (safety_peek(
                &frame)) {

            if (frame.target_bus ==
                0U) {

                int rc =
                    tx_buffer(
                        g_can0,
                        0U,
                        &frame);

                if (rc == 0) {

                    uint64_t latency =
                        monotonic_ns() -
                        frame.rx_timestamp_ns;

                    (void)safety_pop(
                        &frame);

                    pthread_mutex_lock(
                        &g_stats.lock);

                    ++g_stats.tx_can0;
                    ++g_stats.safety_commands;

                    g_stats.safety_latency_sum_ns +=
                        latency;

                    if (g_stats.safety_latency_min_ns ==
                        UINT64_MAX ||
                        latency <
                        g_stats.safety_latency_min_ns) {

                        g_stats.safety_latency_min_ns =
                            latency;
                    }

                    if (latency >
                        g_stats.safety_latency_max_ns) {

                        g_stats.safety_latency_max_ns =
                            latency;
                    }

                    if (ns_to_ms(latency) >
                        SAFETY_DEADLINE_MS) {

                        ++g_stats.deadline_misses;
                    }

                    pthread_mutex_unlock(
                        &g_stats.lock);

                    continue;

                } else if (rc == EBUSY) {

                    pthread_mutex_lock(
                        &g_stats.lock);

                    ++g_stats.tx_busy;

                    pthread_mutex_unlock(
                        &g_stats.lock);

                } else {

                    pthread_mutex_lock(
                        &g_stats.lock);

                    ++g_stats.tx_failures;

                    pthread_mutex_unlock(
                        &g_stats.lock);
                }
            }
        }

        /*
         * NORMAL routed traffic.
         */
        if (normal_peek(
                &frame,
                0U)) {

            int rc =
                tx_buffer(
                    g_can0,
                    1U,
                    &frame);

            if (rc == 0) {

                normal_drop_target(
                    0U);

                pthread_mutex_lock(
                    &g_stats.lock);

                ++g_stats.tx_can0;
                ++g_stats.normal_forwarded;

                pthread_mutex_unlock(
                    &g_stats.lock);

                continue;
            }
        }

        /*
         * LOW-priority noise.
         */
        if (noise_peek(
                &frame,
                0U)) {

            int rc =
                tx_buffer(
                    g_can0,
                    2U,
                    &frame);

            if (rc == 0) {

                noise_drop_target(
                    0U);

                pthread_mutex_lock(
                    &g_stats.lock);

                ++g_stats.tx_can0;
                ++g_stats.noise_forwarded;

                pthread_mutex_unlock(
                    &g_stats.lock);

                continue;
            }
        }

        usleep(TX_POLL_US);
    }

    return NULL;
}

