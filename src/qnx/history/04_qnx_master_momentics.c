static void *archive_thread(void *arg)
{
    (void)arg;

    pin_current_thread(3U);

    while (g_running ||
           error_size() != 0U) {

        prediction_record_t batch[
            ERROR_BATCH_SIZE];

        unsigned count =
            error_take_batch(
                batch,
                ERROR_BATCH_SIZE);

        /*
         * ERROR FIRST.
         */
        if (count != 0U) {

            archive_batch(
                batch,
                count);

            continue;
        }

        /*
         * Correct records are only a current snapshot.
         */
        {
            prediction_record_t latest;

            if (latest_corrected_snapshot(
                    &latest)) {

                write_latest_corrected(
                    &latest);
            }
        }

        usleep(
            ARCHIVE_PERIOD_MS *
            1000U);
    }

    return NULL;
}

