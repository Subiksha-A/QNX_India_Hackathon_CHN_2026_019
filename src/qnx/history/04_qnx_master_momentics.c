static void noise_drop_target(
    uint8_t target_bus)
{
    uint16_t index;
    uint16_t i;

    pthread_mutex_lock(
        &g_q_noise.lock);

    if (g_q_noise.count == 0U) {
        pthread_mutex_unlock(
            &g_q_noise.lock);
        return;
    }

    if (g_q_noise.ring[
            g_q_noise.head].target_bus ==
        target_bus) {

        g_q_noise.head =
            (uint16_t)(
                (g_q_noise.head + 1U) %
                NOISE_Q_SIZE);

        --g_q_noise.count;

        pthread_mutex_unlock(
            &g_q_noise.lock);

        return;
    }

    index = g_q_noise.head;

    for (i = 0U;
         i < g_q_noise.count;
         ++i) {

        if (g_q_noise.ring[index].target_bus ==
            target_bus) {

            uint16_t current = index;
            uint16_t next =
                (uint16_t)(
                    (current + 1U) %
                    NOISE_Q_SIZE);

            while (current !=
                   g_q_noise.head) {

                g_q_noise.ring[current] =
                    g_q_noise.ring[next];

                current = next;

                next =
                    (uint16_t)(
                        (next + 1U) %
                        NOISE_Q_SIZE);
            }

            g_q_noise.tail =
                (uint16_t)(
                    (g_q_noise.tail +
                     NOISE_Q_SIZE - 1U) %
                    NOISE_Q_SIZE);

            --g_q_noise.count;

            pthread_mutex_unlock(
                &g_q_noise.lock);

            return;
        }

        index =
            (uint16_t)(
                (index + 1U) %
                NOISE_Q_SIZE);
    }

    pthread_mutex_unlock(
        &g_q_noise.lock);
}

static bool error_push(
    const prediction_record_t *record)
{
    bool ok = false;

    pthread_mutex_lock(
        &g_q_error.lock);

    if (g_q_error.count <
        ERROR_Q_SIZE) {

        prediction_record_t copy =
            *record;

        copy.logical_addr =
            0x4000U +
            ((uint32_t)g_q_error.tail *
             (uint32_t)sizeof(prediction_record_t));

        g_q_error.ring[
            g_q_error.tail] =
            copy;

        g_q_error.tail =
            (uint16_t)(
                (g_q_error.tail + 1U) %
                ERROR_Q_SIZE);

        ++g_q_error.count;

        ok = true;
    }

    pthread_mutex_unlock(
        &g_q_error.lock);

    if (!ok) {

        pthread_mutex_lock(
            &g_stats.lock);

        ++g_stats.error_overflow;

        pthread_mutex_unlock(
            &g_stats.lock);
    }

    return ok;
}

static unsigned error_take_batch(
    prediction_record_t *records,
    unsigned maximum)
{
    unsigned count = 0U;

    pthread_mutex_lock(
        &g_q_error.lock);

    while (count < maximum &&
           g_q_error.count != 0U) {

        records[count] =
            g_q_error.ring[
                g_q_error.head];

        g_q_error.head =
            (uint16_t)(
                (g_q_error.head + 1U) %
                ERROR_Q_SIZE);

        --g_q_error.count;

        ++count;
    }

    pthread_mutex_unlock(
        &g_q_error.lock);

    return count;
}

