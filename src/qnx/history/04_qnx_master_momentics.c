static bool gzip_available(void)
{
    return access(
               "/usr/bin/gzip",
               X_OK) == 0 ||
           access(
               "/bin/gzip",
               X_OK) == 0;
}

static int write_all(
    int fd,
    const char *data,
    size_t length)
{
    size_t offset = 0U;

    while (offset <
           length) {

        ssize_t n =
            write(
                fd,
                data + offset,
                length - offset);

        if (n < 0) {

            if (errno ==
                EINTR) {

                continue;
            }

            return -1;
        }

        offset +=
            (size_t)n;
    }

    return 0;
}

static void gzip_file(
    const char *path)
{
    char command[512];

    if (!gzip_available()) {
        return;
    }

    if (access(
            "/usr/bin/gzip",
            X_OK) == 0) {

        (void)snprintf(
            command,
            sizeof(command),
            "/usr/bin/gzip -f \"%s\"",
            path);

    } else {

        (void)snprintf(
            command,
            sizeof(command),
            "/bin/gzip -f \"%s\"",
            path);
    }

    /*
     * IMPORTANT:
     * Called ONLY by P5 archive thread.
     */
    (void)system(command);
}

static void archive_batch(
    prediction_record_t *records,
    unsigned count)
{
    char raw_path[256];
    char gz_path[256];
    char final_path[256];

    int fd;

    unsigned i;

    if (count == 0U) {
        return;
    }

    (void)snprintf(
        raw_path,
        sizeof(raw_path),
        "/tmp/qnx_master/staging/"
        "error_batch_%06llu.csv",
        (unsigned long long)
            g_archive_sequence);

    fd =
        open(raw_path,
             O_WRONLY |
             O_CREAT |
             O_TRUNC,
             0666);

    if (fd < 0) {
        return;
    }

    {
        static const char header[] =
            "seq,node_id,can_id,logical_address,"
            "sensor,predicted,actual,error,tolerance,"
            "timestamp_ns\n";

        (void)write_all(
            fd,
            header,
            strlen(header));
    }

    for (i = 0U;
         i < count;
         ++i) {

        char line[512];

        (void)snprintf(
            line,
            sizeof(line),
            "%llu,%u,0x%03X,0x%08X,%s,"
            "%.3f,%.3f,%.3f,%.3f,%llu\n",

            (unsigned long long)
                records[i].sequence,

            records[i].node_id,

            records[i].can_id,

            records[i].logical_addr,

            sensor_name(
                records[i].sensor),

            records[i].predicted,

            records[i].actual,

            records[i].error,

            records[i].tolerance,

            (unsigned long long)
                records[i].timestamp_ns);

        (void)write_all(
            fd,
            line,
            strlen(line));
    }

    (void)fsync(fd);

    close(fd);

    gzip_file(raw_path);

    (void)snprintf(
        gz_path,
        sizeof(gz_path),
        "%s.gz",
        raw_path);

    if (access(
            gz_path,
            F_OK) == 0) {

        (void)snprintf(
            final_path,
            sizeof(final_path),
            "/tmp/qnx_master/errors/archive/"
            "error_batch_%06llu.csv.gz",
            (unsigned long long)
                g_archive_sequence);

        (void)rename(
            gz_path,
            final_path);

    } else {

        (void)snprintf(
            final_path,
            sizeof(final_path),
            "/tmp/qnx_master/errors/archive/"
            "error_batch_%06llu.csv",
            (unsigned long long)
                g_archive_sequence);

        (void)rename(
            raw_path,
            final_path);
    }

    pthread_mutex_lock(
        &g_stats.lock);

    g_stats.wrong_archived +=
        count;

    pthread_mutex_unlock(
        &g_stats.lock);

    ++g_archive_sequence;
}

