static bool safety_push(const gateway_frame_t *frame)
{
    bool ok = false;

    pthread_mutex_lock(&g_q_safety.lock);

    if (g_q_safety.count <
        SAFETY_Q_SIZE) {

        gateway_frame_t copy =
            *frame;

        copy.logical_addr =
            0x0800U +
            ((uint32_t)g_q_safety.tail *
             (uint32_t)sizeof(gateway_frame_t));

        g_q_safety.ring[
            g_q_safety.tail] =
            copy;

        g_q_safety.tail =
            (uint16_t)(
                (g_q_safety.tail + 1U) %
                SAFETY_Q_SIZE);

        ++g_q_safety.count;

        ok = true;
    }

    pthread_mutex_unlock(
        &g_q_safety.lock);

    return ok;
}

static bool safety_peek(
    gateway_frame_t *frame)
{
    bool ok = false;

    pthread_mutex_lock(
        &g_q_safety.lock);

    if (g_q_safety.count != 0U) {

        *frame =
            g_q_safety.ring[
                g_q_safety.head];

        ok = true;
    }

    pthread_mutex_unlock(
        &g_q_safety.lock);

    return ok;
}

