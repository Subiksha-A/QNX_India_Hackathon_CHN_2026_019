/*
 * qnx_master_momentics.c
 *
 * QNX 8.x / Raspberry Pi 4 / Momentics
 *
 * PROJECT:
 *   Dual-CAN vehicle gateway:
 *      CAN0 <-> FRDM-MCXA156 / Node 1
 *      CAN1 <-> FRDM-MCXA236 / Node 2
 *
 * NXP protocol implemented from the supplied MCXA156 source:
 *
 * Node 1:
 *   0x111 Temperature
 *   0x112 Humidity
 *   0x113 Speed
 *   0x114 Battery voltage
 *   0x115 Battery current
 *   0x116 Ultrasonic distance
 *   0x117 IR obstacle
 *   0x201 Node-1 START/STOP command
 *
 * Node 2 branch in the supplied protocol:
 *   0x121..0x125 corresponding normal sensor frames
 *   0x202 Node-2 START/STOP command
 *
 * Broadcast command:
 *   0x200
 *
 * Normal sensor payload:
 *   byte 0..1 = value * 100, big endian
 *   byte 2    = sensor type
 *   byte 3    = node ID
 *   byte 4..7 = reserved
 *
 * IR payload:
 *   byte 0 = 0 clear / 1 obstacle
 *   byte 2 = 0x07
 *   byte 3 = node ID
 *
 * NXP CAN bitrate:
 *   500 kbps
 *
 * NXP sensor period:
 *   500 ms
 *
 * QNX architecture:
 *   CPU0 : Safety + CAN0 TX
 *   CPU1 : CAN0 RX / MCXA156
 *   CPU2 : CAN1 RX / MCXA236
 *   CPU3 : CAN1 TX + Diagnostics
 *
 * RT priority:
 *   P60 Safety preparation
 *   P55 CAN TX schedulers
 *   P50 CAN RX
 *   P15 Diagnostics
 *   P10 Congestion generator
 *   P5  Error archive
 *
 * Memory architecture:
 *   logical data/address/memory banks
 *   fixed-size queues
 *   no per-frame malloc in CAN/SPI path
 *
 * Fault-analysis policy:
 *   WRONG prediction -> historical fixed error ring -> CSV -> gzip
 *   CORRECT prediction -> only latest corrected record
 *
 * NOTE:
 *   Data bus / address bus / memory bus are logical software abstractions
 *   for the architecture presentation. They are not physical Pi CPU buses.
 *
 * Build:
 *   qcc -Wall -Wextra -O2 qnx_master_momentics.c \
 *       -o qnx_master -lsocket -lm
 */

