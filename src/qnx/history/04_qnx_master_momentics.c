/* ========================================================================== */
/* RT thread creation                                                         */
/* ========================================================================== */

static int create_rt_thread(
    pthread_t *thread,
    void *(*entry)(void *),
    int priority,
    const char *name)
{
    pthread_attr_t attr;
    struct sched_param param;

    int rc;

    (void)pthread_attr_init(
        &attr);

    (void)pthread_attr_setinheritsched(
        &attr,
        PTHREAD_EXPLICIT_SCHED);

    (void)pthread_attr_setschedpolicy(
        &attr,
        SCHED_FIFO);

    memset(&param,
           0,
           sizeof(param));

    param.sched_priority =
        priority;

    (void)pthread_attr_setschedparam(
        &attr,
        &param);

    rc =
        pthread_create(
            thread,
            &attr,
            entry,
            NULL);

    (void)pthread_attr_destroy(
        &attr);

    if (rc != 0) {

        fprintf(stderr,
                "[-] thread %s P%d: %s\n",
                name,
                priority,
                strerror(rc));

        return rc;
    }

    printf(
        "[+] %-20s SCHED_FIFO P%d\n",
        name,
        priority);

    return 0;
}

/* ========================================================================== */
/* UDP                                                                        */
/* ========================================================================== */

static void init_udp(void)
{
    int broadcast = 1;

    g_udp =
        socket(
            AF_INET,
            SOCK_DGRAM,
            0);

    if (g_udp < 0) {
        return;
    }

    (void)setsockopt(
        g_udp,
        SOL_SOCKET,
        SO_BROADCAST,
        &broadcast,
        sizeof(broadcast));

    memset(
        &g_dashboard,
        0,
        sizeof(g_dashboard));

    g_dashboard.sin_family =
        AF_INET;

    g_dashboard.sin_port =
        htons(UDP_PORT);

    g_dashboard.sin_addr.s_addr =
        inet_addr(UDP_BROADCAST);
}

/* ========================================================================== */
/* Main                                                                       */
/* ========================================================================== */

int main(void)
{
    long cpu_result;

    cpu_result =
        sysconf(
            _SC_NPROCESSORS_ONLN);

    if (cpu_result > 0L) {
        g_cpu_count =
            (unsigned)cpu_result;
    }

    (void)signal(
        SIGINT,
        signal_handler);

    (void)signal(
        SIGTERM,
        signal_handler);

    printf(
        "============================================================\n"
        " QNX MASTER / MOMENTICS - DUAL NXP CAN GATEWAY\n"
        "============================================================\n"
        "CAN0 : FRDM-MCXA156 / Node 1\n"
        "CAN1 : FRDM-MCXA236 / Node 2\n"
        "CAN bitrate : %u bps\n"
        "Sensor cycle: %u ms\n"
        "CPUs        : %u\n"
        "============================================================\n",
        CAN_BITRATE,
        500U,
        g_cpu_count);

    init_storage();

    memset(
        &g_q_safety,
        0,
        sizeof(g_q_safety));

    memset(
        &g_q_normal,
        0,
        sizeof(g_q_normal));

    memset(
        &g_q_noise,
        0,
        sizeof(g_q_noise));

    memset(
        &g_q_error,
        0,
        sizeof(g_q_error));

    memset(
        &g_latest_corrected,
        0,
        sizeof(g_latest_corrected));

    init_pi_mutex(
        &g_q_safety.lock);

    init_pi_mutex(
        &g_q_normal.lock);

    init_pi_mutex(
        &g_q_noise.lock);

    init_pi_mutex(
        &g_q_error.lock);

    init_pi_mutex(
        &g_latest_corrected.lock);

    init_pi_mutex(
        &g_stats.lock);

    init_pi_mutex(
        &g_memory_bus_lock);

    memset(
        g_latest_state,
        0,
        sizeof(g_latest_state));

    memset(
        g_history_valid,
        0,
        sizeof(g_history_valid));

    g_stats.safety_latency_min_ns =
        UINT64_MAX;

    print_architecture();

    g_can0 =
        init_can(
            CAN0_DEV,
            "CAN0 / MCXA156");

    g_can1 =
        init_can(
            CAN1_DEV,
            "CAN1 / MCXA236");

    if (g_can0 < 0 ||
        g_can1 < 0) {

        fprintf(stderr,
                "[-] CAN initialization failed\n");

        if (g_can0 >= 0) {
            close(g_can0);
        }

        if (g_can1 >= 0) {
            close(g_can1);
        }

        return EXIT_FAILURE;
    }

    init_udp();

    /*
     * P60 Safety
     * P55 CAN TX
     * P50 CAN RX
     * P15 Diagnostics
     * P10 Noise
     * P5  Archive
     */
    if (create_rt_thread(
            &g_th_safety,
            safety_thread,
            60,
            "Safety") != 0) {

        return EXIT_FAILURE;
    }

    if (create_rt_thread(
            &g_th_tx0,
            can0_tx_thread,
            55,
            "CAN0 TX") != 0) {

        return EXIT_FAILURE;
    }

    if (create_rt_thread(
            &g_th_tx1,
            can1_tx_thread,
            55,
            "CAN1 TX") != 0) {

        return EXIT_FAILURE;
    }

    if (create_rt_thread(
            &g_th_rx0,
            can0_rx_thread,
            50,
            "CAN0 RX") != 0) {

        return EXIT_FAILURE;
    }

    if (create_rt_thread(
            &g_th_rx1,
            can1_rx_thread,
            50,
            "CAN1 RX") != 0) {

        return EXIT_FAILURE;
    }

    if (create_rt_thread(
            &g_th_diag,
            diagnostics_thread,
            15,
            "Diagnostics") != 0) {

        return EXIT_FAILURE;
    }

    if (create_rt_thread(
            &g_th_noise,
            noise_thread,
            10,
            "Congestion") != 0) {

        return EXIT_FAILURE;
    }

    if (create_rt_thread(
            &g_th_archive,
            archive_thread,
            5,
            "Error Archive") != 0) {

        return EXIT_FAILURE;
    }

    printf(
        "\n====================== MENU ======================\n"
        "1  START Node 1  -> 0x201 / D0=0x01\n"
        "2  STOP  Node 1  -> 0x201 / D0=0x00\n"
        "3  START Node 2  -> 0x202 / D0=0x01\n"
        "4  STOP  Node 2  -> 0x202 / D0=0x00\n"
        "5  Show decoded sensor readings\n"
        "6  Toggle CAN congestion/noise\n"
        "7  Clear safety latches\n"
        "8  Show memory / bus architecture\n"
        "9  Quit\n"
        "==================================================\n");

    while (g_running) {

        int c;

        printf(
            "\nSelect [1-9]: ");

        fflush(stdout);

        c = getchar();

        if (c == EOF) {
            break;
        }

        if (c == '\n') {
            continue;
        }

        switch (c) {

            case '1':

                send_start_stop(
                    NODE1_ID,
                    CMD_START);

                break;

            case '2':

                send_start_stop(
                    NODE1_ID,
                    CMD_STOP);

                break;

            case '3':

                send_start_stop(
                    NODE2_ID,
                    CMD_START);

                break;

            case '4':

                send_start_stop(
                    NODE2_ID,
                    CMD_STOP);

                break;

            case '5':

                print_sensor_state();

                break;

            case '6':

                g_congestion =
                    !g_congestion;

                printf(
                    "[MASTER] congestion/noise = %s\n",
                    g_congestion ?
                        "ON" :
                        "OFF");

                break;

            case '7':

                clear_safety_latches();

                break;

            case '8':

                print_architecture();

                break;

            case '9':

                g_running =
                    0;

                break;

            default:

                printf(
                    "[MASTER] invalid option\n");

                break;
        }

        while (c != '\n' &&
               c != EOF) {

            c = getchar();
        }
    }

    g_running =
        0;

    printf(
        "\n[MASTER] stopping...\n");

    (void)pthread_join(
        g_th_safety,
        NULL);

    (void)pthread_join(
        g_th_tx0,
        NULL);

    (void)pthread_join(
        g_th_tx1,
        NULL);

    (void)pthread_join(
        g_th_rx0,
        NULL);

    (void)pthread_join(
        g_th_rx1,
        NULL);

    (void)pthread_join(
        g_th_diag,
        NULL);

    (void)pthread_join(
        g_th_noise,
        NULL);

    (void)pthread_join(
        g_th_archive,
        NULL);

    if (g_can0 >= 0) {
        close(g_can0);
    }

    if (g_can1 >= 0) {
        close(g_can1);
    }

    if (g_udp >= 0) {
        close(g_udp);
    }

    printf(
        "[MASTER] stopped.\n"
        "Wrong prediction archive : "
        "/tmp/qnx_master/errors/archive/\n"
        "Latest corrected         : "
        "/tmp/qnx_master/corrected/latest_corrected.json\n");

    return EXIT_SUCCESS;
}
