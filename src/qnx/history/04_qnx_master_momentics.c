/*
 * The normal queue is one ring shared by both targets.
 * Remove the head only when it belongs to the requested target.
 */
static void normal_drop_target(
    uint8_t target_bus)
{
    uint16_t index;
    uint16_t i;

    pthread_mutex_lock(
        &g_q_normal.lock);

    if (g_q_normal.count == 0U) {
        pthread_mutex_unlock(
            &g_q_normal.lock);
        return;
    }

    if (g_q_normal.ring[
            g_q_normal.head].target_bus ==
        target_bus) {

        g_q_normal.head =
            (uint16_t)(
                (g_q_normal.head + 1U) %
                NORMAL_Q_SIZE);

        --g_q_normal.count;

        pthread_mutex_unlock(
            &g_q_normal.lock);

        return;
    }

    /*
     * If the head belongs to the other CAN bus, search for the first
     * frame for this bus and compact the bounded ring.
     */
    index = g_q_normal.head;

    for (i = 0U;
         i < g_q_normal.count;
         ++i) {

        if (g_q_normal.ring[index].target_bus ==
            target_bus) {

            uint16_t current = index;
            uint16_t previous =
                (uint16_t)(
                    (current +
                     NORMAL_Q_SIZE - 1U) %
                    NORMAL_Q_SIZE);

            while (current !=
                   g_q_normal.head) {

                g_q_normal.ring[current] =
                    g_q_normal.ring[previous];

                current = previous;

                previous =
                    (uint16_t)(
                        (previous +
                         NORMAL_Q_SIZE - 1U) %
                        NORMAL_Q_SIZE);
            }

            g_q_normal.head =
                (uint16_t)(
                    (g_q_normal.head + 1U) %
                    NORMAL_Q_SIZE);

            --g_q_normal.count;

            pthread_mutex_unlock(
                &g_q_normal.lock);

            return;
        }

        index =
            (uint16_t)(
                (index + 1U) %
                NORMAL_Q_SIZE);
    }

    pthread_mutex_unlock(
        &g_q_normal.lock);
}

