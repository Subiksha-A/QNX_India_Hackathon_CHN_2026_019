/* THREAD: congestion generator P10                                           */
/* ========================================================================== */

static void *noise_thread(void *arg)
{
    (void)arg;

    pin_current_thread(2U);

    while (g_running) {

        if (!g_congestion) {

            usleep(1000U);

            continue;
        }

        /*
         * Produce noise on both CAN domains so load-shedding is visible
         * independently on both network sides.
         */
        {
            gateway_frame_t frame0;
            gateway_frame_t frame1;

            memset(&frame0,
                   0,
                   sizeof(frame0));

            frame0.can_id =
                ID_CONGESTION_NOISE;

            frame0.dlc =
                8U;

            frame0.source_bus =
                0U;

            frame0.target_bus =
                1U;

            frame0.rx_timestamp_ns =
                monotonic_ns();

            frame0.data[0] =
                0xA5U;

            frame0.data[1] =
                0x5AU;

            memset(&frame1,
                   0,
                   sizeof(frame1));

            frame1.can_id =
                ID_CONGESTION_NOISE;

            frame1.dlc =
                8U;

            frame1.source_bus =
                1U;

            frame1.target_bus =
                0U;

            frame1.rx_timestamp_ns =
                monotonic_ns();

            frame1.data[0] =
                0x5AU;

            frame1.data[1] =
                0xA5U;

            if (noise_size() >=
                (NOISE_Q_SIZE *
                 NOISE_SHED_PERCENT) /
                100U) {

                pthread_mutex_lock(
                    &g_stats.lock);

                g_stats.noise_dropped +=
                    2U;

                pthread_mutex_unlock(
                    &g_stats.lock);

            } else {

                (void)noise_push(
                    &frame0);

                (void)noise_push(
                    &frame1);
            }
        }

        usleep(100U);
    }

    return NULL;
}

